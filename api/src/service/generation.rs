/// Answers one user can have generated at the same time, across all chats.
const MAX_GENERATIONS_PER_USER: usize = 3;

/// Events buffered per subscriber. A subscriber that falls further behind is disconnected,
/// and starts again from a fresh snapshot when it reconnects.
const EVENT_BUFFER: usize = 256;

/// Separates the text of consecutive LLM responses.
pub(crate) const PARAGRAPH_BREAK: &str = "\n\n";

const INTERRUPTED_ERROR: &str = "The answer was interrupted by a server restart";
const INTERNAL_ERROR: &str = "Something went wrong while generating the answer";

/// The answers being generated by this process. In-memory, so it assumes a single API instance.
///
/// A generation is registered before its `GENERATING` message is inserted and removed after the
/// message is finished, so every `GENERATING` message has a live generation.
#[derive(Default)]
pub(crate) struct GenerationRegistry {
    live: Mutex<HashMap<Uuid, Arc<Generation>>>,
    /// Set on shutdown, after which no generation is started anymore.
    closed: AtomicBool,
}

impl GenerationRegistry {
    /// Registers the generation of `message_id`, written by `model`. Call [`Self::release`]
    /// if the message is not inserted after all.
    pub(crate) fn reserve(
        &self,
        user_id: Uuid,
        chat_id: Uuid,
        message_id: Uuid,
        model: &AnsweringModel,
        client: ClientContext,
        created_at: DateTime<Utc>,
    ) -> Result<Arc<Generation>, AppError> {
        let mut live = self.live.lock().unwrap();
        if self.closed.load(Ordering::SeqCst) {
            return Err(AppError::Unavailable(
                "The server is shutting down, please try again later".to_string(),
            ));
        }
        if live.values().filter(|g| g.user_id == user_id).count() >= MAX_GENERATIONS_PER_USER {
            return Err(AppError::TooManyRequests(format!(
                "At most {MAX_GENERATIONS_PER_USER} answers can be generated at the same time"
            )));
        }
        let generation = Arc::new(Generation {
            message_id,
            chat_id,
            user_id,
            client,
            model_id: model.id,
            pricing: model.pricing.clone(),
            created_at,
            state: Mutex::new(GenerationState::default()),
            events: broadcast::channel(EVENT_BUFFER).0,
            cancel: CancellationToken::new(),
        });
        live.insert(message_id, generation.clone());
        Ok(generation)
    }

    pub(crate) fn release(&self, message_id: Uuid) {
        self.live.lock().unwrap().remove(&message_id);
    }

    pub(crate) fn get(&self, message_id: Uuid) -> Option<Arc<Generation>> {
        self.live.lock().unwrap().get(&message_id).cloned()
    }

    pub(crate) fn of_chat(&self, chat_id: Uuid) -> Vec<Arc<Generation>> {
        self.live
            .lock()
            .unwrap()
            .values()
            .filter(|g| g.chat_id == chat_id)
            .cloned()
            .collect()
    }

    /// Rejects new generations and returns the live ones.
    fn close(&self) -> Vec<Arc<Generation>> {
        let live = self.live.lock().unwrap();
        self.closed.store(true, Ordering::SeqCst);
        live.values().cloned().collect()
    }
}

/// What the request that starts a generation tells about the user's device.
pub(crate) struct ClientContext {
    /// From the request's `Accept-Language`, used when the user has not chosen a locale.
    pub locale: Option<String>,
    /// `None` if the client did not send it.
    pub utc_offset: Option<FixedOffset>,
}

pub(crate) struct Generation {
    pub message_id: Uuid,
    pub chat_id: Uuid,
    pub user_id: Uuid,
    pub client: ClientContext,
    model_id: Uuid,
    /// Prices of the model when the message was sent, `None` if it has none.
    pricing: Option<Pricing>,
    created_at: DateTime<Utc>,
    state: Mutex<GenerationState>,
    events: broadcast::Sender<GenerationEvent>,
    cancel: CancellationToken,
}

#[derive(Default)]
struct GenerationState {
    content: String,
    /// Where the answer starts in `content`. The text before it is a preamble to tool calls,
    /// shown while generating and dropped when the message is finished.
    answer_start: usize,
    tool_calls: Vec<ToolCallSummary>,
    /// Of the LLM responses so far. A response that was cut off (e.g. cancelled) reports none.
    usage: Usage,
    /// Set by the first [`finish`], after which nothing is appended anymore.
    finished: bool,
    /// The final message, once [`GenerationEvent::Done`] was sent.
    done: Option<(Message, Vec<ToolCallSummary>)>,
}

impl GenerationState {
    /// The content after the preamble, without the paragraph break that separates them.
    fn answer(&self) -> &str {
        let answer = &self.content[self.answer_start..];
        answer.strip_prefix(PARAGRAPH_BREAK).unwrap_or(answer)
    }
}

#[derive(Clone)]
pub(crate) enum GenerationEvent {
    ContentDelta(String),
    ToolCallStarted(ToolCallSummary),
    ToolCallFinished {
        id: Uuid,
        is_error: bool,
    },
    /// The final message, sent once.
    Done {
        message: Message,
        tool_calls: Vec<ToolCallSummary>,
    },
}

pub(crate) enum Subscription {
    /// The state so far; `events` receives everything after it.
    Live {
        message: Message,
        tool_calls: Vec<ToolCallSummary>,
        events: broadcast::Receiver<GenerationEvent>,
    },
    Done {
        message: Message,
        tool_calls: Vec<ToolCallSummary>,
    },
}

pub(crate) enum GenerationError {
    /// The generation was finished elsewhere: cancelled, or the chat was deleted.
    Stopped,
    /// Shown to the user, keep details in the logs.
    Failed(String),
}

impl From<AppError> for GenerationError {
    fn from(e: AppError) -> Self {
        tracing::error!("Answer generation failed: {e}");
        GenerationError::Failed(INTERNAL_ERROR.to_string())
    }
}

impl Generation {
    pub(crate) fn subscribe(&self) -> Subscription {
        // Holding the lock while subscribing ensures no event is missed or sent twice.
        let state = self.state.lock().unwrap();
        if let Some((message, tool_calls)) = &state.done {
            return Subscription::Done {
                message: message.clone(),
                tool_calls: tool_calls.clone(),
            };
        }
        Subscription::Live {
            message: Message {
                id: self.message_id,
                role: MessageRole::Assistant,
                content: state.content.clone(),
                status: MessageStatus::Generating,
                error: None,
                model_id: Some(self.model_id),
                created_at: self.created_at,
                finished_at: None,
                input_tokens: None,
                output_tokens: None,
                cache_read_tokens: None,
                cache_write_tokens: None,
                cost: None,
                cost_currency: None,
            },
            tool_calls: state.tool_calls.clone(),
            events: self.events.subscribe(),
        }
    }

    /// Resolves when the generation is cancelled or otherwise finished elsewhere.
    pub(crate) fn cancelled(&self) -> WaitForCancellationFuture<'_> {
        self.cancel.cancelled()
    }

    /// Adds the usage of one LLM response.
    pub(crate) fn add_usage(&self, usage: &Usage) -> Result<(), GenerationError> {
        let mut state = self.state.lock().unwrap();
        if state.finished {
            return Err(GenerationError::Stopped);
        }
        state.usage += usage;
        Ok(())
    }

    pub(crate) fn append_content(&self, text: &str) -> Result<(), GenerationError> {
        let mut state = self.state.lock().unwrap();
        if state.finished {
            return Err(GenerationError::Stopped);
        }
        state.content.push_str(text);
        let _ = self
            .events
            .send(GenerationEvent::ContentDelta(text.to_string()));
        Ok(())
    }

    pub(crate) fn has_content(&self) -> bool {
        !self.state.lock().unwrap().content.is_empty()
    }

    /// Marks the content so far as a preamble, e.g. the "Let me look" of a response that calls
    /// tools. It stays visible while generating and is dropped when the message is finished.
    pub(crate) fn mark_preamble(&self) -> Result<(), GenerationError> {
        let mut state = self.state.lock().unwrap();
        if state.finished {
            return Err(GenerationError::Stopped);
        }
        state.answer_start = state.content.len();
        Ok(())
    }

    /// Stores a running tool call and returns its id.
    pub(crate) async fn start_tool_call(
        &self,
        db: &DatabasePool,
        name: &str,
        input: serde_json::Value,
        repository_id: Option<Uuid>,
        commit_sha: Option<&str>,
    ) -> Result<Uuid, GenerationError> {
        let id = Uuid::now_v7();
        let created_at = Utc::now();
        let inserted = repository::message::insert_tool_call(
            db,
            NewToolCall {
                id,
                message_id: self.message_id,
                name,
                input: &input,
                repository_id,
                commit_sha,
                created_at,
            },
        )
        .await?;
        if !inserted {
            return Err(GenerationError::Stopped);
        }

        let mut state = self.state.lock().unwrap();
        if state.finished {
            return Err(GenerationError::Stopped);
        }
        let tool_call = ToolCallSummary {
            id,
            message_id: self.message_id,
            name: name.to_string(),
            input,
            repository_id,
            commit_sha: commit_sha.map(str::to_string),
            finished: false,
            is_error: false,
            created_at,
        };
        state.tool_calls.push(tool_call.clone());
        let _ = self
            .events
            .send(GenerationEvent::ToolCallStarted(tool_call));
        Ok(id)
    }

    pub(crate) async fn finish_tool_call(
        &self,
        db: &DatabasePool,
        id: Uuid,
        output: &str,
        is_error: bool,
        change: Option<&ProposedChange>,
    ) -> Result<(), GenerationError> {
        if !repository::message::finish_tool_call(db, id, output, is_error, change).await? {
            return Err(GenerationError::Stopped);
        }

        let mut state = self.state.lock().unwrap();
        if state.finished {
            return Err(GenerationError::Stopped);
        }
        if let Some(tool_call) = state.tool_calls.iter_mut().find(|t| t.id == id) {
            tool_call.finished = true;
            tool_call.is_error = is_error;
        }
        let _ = self
            .events
            .send(GenerationEvent::ToolCallFinished { id, is_error });
        Ok(())
    }
}

/// Generates the answer with the model of `llm` in the background and finishes the message
/// afterwards.
pub(crate) fn spawn(state: AppState, generation: Arc<Generation>, llm: LlmConfig) {
    tokio::spawn(async move {
        let task = tokio::spawn({
            let state = state.clone();
            let generation = generation.clone();
            async move { answer::generate(&state, &generation, &llm).await }
        });
        let (status, error) = match task.await {
            Ok(Ok(())) => (MessageStatus::Completed, None),
            Ok(Err(GenerationError::Stopped)) => return,
            Ok(Err(GenerationError::Failed(error))) => (MessageStatus::Failed, Some(error)),
            Err(e) => {
                tracing::error!(
                    "Answer generation of message {} panicked: {e}",
                    generation.message_id
                );
                (MessageStatus::Failed, Some(INTERNAL_ERROR.to_string()))
            }
        };
        if let Err(e) = finish(&state, &generation, status, error.as_deref()).await {
            tracing::error!("Failed to finish message {}: {e}", generation.message_id);
        }
    });
}

/// Moves the message to its final `status`, sends [`GenerationEvent::Done`] and stops the
/// generation. Only the first call has an effect.
pub(crate) async fn finish(
    state: &AppState,
    generation: &Generation,
    status: MessageStatus,
    error: Option<&str>,
) -> Result<(), AppError> {
    let (content, usage) = {
        let mut generation_state = generation.state.lock().unwrap();
        if generation_state.finished {
            return Ok(());
        }
        generation_state.finished = true;
        (
            generation_state.answer().to_string(),
            generation_state.usage.clone(),
        )
    };
    generation.cancel.cancel();

    let cost = generation
        .pricing
        .as_ref()
        .map(|pricing| (pricing.cost(&usage), pricing.currency.as_str()));
    let finished = FinishedMessage {
        status,
        content: Some(&content),
        error,
        usage: Some(token_usage(&usage)),
        cost,
        finished_at: Utc::now(),
    };
    let result = store_final_message(state, generation.message_id, finished).await;
    if let Ok(Some((message, tool_calls))) = &result {
        let mut generation_state = generation.state.lock().unwrap();
        let _ = generation.events.send(GenerationEvent::Done {
            message: message.clone(),
            tool_calls: tool_calls.clone(),
        });
        generation_state.done = Some((message.clone(), tool_calls.clone()));
    }
    // Released even on errors, so a message stuck in `GENERATING` can still be cancelled.
    state.generations.release(generation.message_id);
    result.map(|_| ())
}

/// Keeps the partial content. Does nothing if the message is no longer `GENERATING`.
pub(crate) async fn cancel(state: &AppState, message_id: Uuid) -> Result<(), AppError> {
    match state.generations.get(message_id) {
        Some(generation) => finish(state, &generation, MessageStatus::Cancelled, None).await,
        // A message whose generation failed to finish it is cancelled directly.
        None => {
            let finished = FinishedMessage {
                status: MessageStatus::Cancelled,
                content: None,
                error: None,
                usage: None,
                cost: None,
                finished_at: Utc::now(),
            };
            repository::message::finish_message(&state.db, message_id, finished).await?;
            Ok(())
        }
    }
}

/// Stops the generations of a deleted chat.
pub(crate) async fn stop_chat(state: &AppState, chat_id: Uuid) {
    for generation in state.generations.of_chat(chat_id) {
        if let Err(e) = finish(state, &generation, MessageStatus::Cancelled, None).await {
            tracing::error!("Failed to stop message {}: {e}", generation.message_id);
        }
    }
}

/// Fails all live generations, like a restart would, and rejects new ones.
pub(crate) async fn stop_all(state: &AppState) {
    for generation in state.generations.close() {
        let result = finish(
            state,
            &generation,
            MessageStatus::Failed,
            Some(INTERRUPTED_ERROR),
        )
        .await;
        if let Err(e) = result {
            tracing::error!("Failed to stop message {}: {e}", generation.message_id);
        }
    }
}

/// Returns `None` if the message was deleted together with its chat.
async fn store_final_message(
    state: &AppState,
    message_id: Uuid,
    finished: FinishedMessage<'_>,
) -> Result<Option<(Message, Vec<ToolCallSummary>)>, AppError> {
    let message = repository::message::finish_message(&state.db, message_id, finished).await?;
    let Some(message) = message else {
        return Ok(None);
    };
    let tool_calls =
        repository::message::list_tool_call_summaries_of_message(&state.db, message_id).await?;
    Ok(Some((message, tool_calls)))
}

fn token_usage(usage: &Usage) -> TokenUsage {
    // Saturates instead of failing the answer, no real answer comes close.
    let tokens = |count: u64| i64::try_from(count).unwrap_or(i64::MAX);
    TokenUsage {
        input: tokens(usage.input_tokens),
        output: tokens(usage.output_tokens),
        cache_read: tokens(usage.cache_read_input_tokens),
        cache_write: tokens(usage.cache_creation_input_tokens),
    }
}

/// Fails the answers that were being generated when the server stopped.
pub(crate) async fn fail_interrupted(db: &DatabasePool) -> Result<u64, AppError> {
    repository::message::fail_interrupted_messages(db, INTERRUPTED_ERROR).await
}
